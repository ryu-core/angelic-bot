def parse_timezone(location_input):
    """
    Parse location input and return timezone name
    Returns tuple: (timezone_name, display_name)
    """
    import pytz
    
    location_lower = location_input.lower().strip()
    
    # Check timezone abbreviations first
    if location_lower in TIMEZONE_ABBREVIATIONS:
        tz_name = TIMEZONE_ABBREVIATIONS[location_lower]
        return (tz_name, location_input.upper())
    
    # Check country names
    if location_lower in COUNTRY_TIMEZONES:
        tz_name = COUNTRY_TIMEZONES[location_lower]
        return (tz_name, location_input.title())
    
    # Check city names
    if location_lower in CITY_TIMEZONES:
        tz_name = CITY_TIMEZONES[location_lower]
        return (tz_name, location_input.title())
    
    # Try as direct timezone name
    try:
        pytz.timezone(location_input)
        return (location_input, location_input)
    except:
        return (None, None)
